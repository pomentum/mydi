// Command forwards writes mydi.go at the module's root: every name src exports, forwarded, so programs import github.com/pomentum/mydi
// while the code lives in src/ (ADR-0001 part A). Types are aliases, constants and variables the same values (a settings struct by its
// address, so a program's change reaches src), functions call src's with the same signature, each with src's documentation. Run from the
// module's root: go run ./src/internal/forwards
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// byAddress are the package variables a program changes in place: forwarded by their address.
var byAddress = map[string]bool{"MeasureHold": true, "MeasureRestart": true}

type decl struct {
	name, kind, doc, text string
	imports               map[string]string
}

func main() {
	fset := token.NewFileSet()
	files, err := filepath.Glob("src/*.go")
	if err != nil || len(files) == 0 {
		fail("run it from the module's root: no src/*.go")
	}
	seen := map[string]decl{}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			fail(err.Error())
		}
		imports := map[string]string{}
		for _, im := range f.Imports {
			p := strings.Trim(im.Path.Value, `"`)
			name := filepath.Base(p)
			if im.Name != nil {
				name = im.Name.Name
			}
			imports[name] = p
		}
		for _, d := range f.Decls {
			for _, one := range declsOf(fset, d, imports) {
				if _, ok := seen[one.name]; !ok {
					seen[one.name] = one
				}
			}
		}
	}
	names := make([]string, 0, len(seen))
	used := map[string]string{"github.com/pomentum/mydi/src": "src"}
	for name, d := range seen {
		names = append(names, name)
		for q, p := range d.imports {
			used[p] = q
		}
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./src/internal/forwards; DO NOT EDIT.\n\n")
	b.WriteString("package mydi\n\nimport (\n")
	paths := make([]string, 0, len(used))
	for p := range used {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%q\n", p)
	}
	b.WriteString(")\n")
	for _, kind := range []string{"const", "var", "type", "func"} {
		for _, name := range names {
			if d := seen[name]; d.kind == kind {
				b.WriteString("\n" + d.doc + d.text + "\n")
			}
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail("the generated file does not format: " + err.Error() + "\n" + b.String())
	}
	if err := os.WriteFile("mydi.go", out, 0o644); err != nil {
		fail(err.Error())
	}
}

// declsOf turns one top-level declaration of src into the forwards of its exported names.
func declsOf(fset *token.FileSet, d ast.Decl, imports map[string]string) []decl {
	var out []decl
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Recv != nil || !d.Name.IsExported() {
			return nil
		}
		used := map[string]string{}
		params := fieldsText(fset, d.Type.Params, imports, used, true)
		results := ""
		if d.Type.Results != nil {
			results = " " + resultsText(fset, d.Type.Results, imports, used)
		}
		call := "src." + d.Name.Name + "(" + argsOf(d.Type.Params) + ")"
		body := call
		if d.Type.Results != nil {
			body = "return " + call
		}
		out = append(out, decl{name: d.Name.Name, kind: "func", doc: docOf(d.Doc),
			text: fmt.Sprintf("func %s(%s)%s { %s }", d.Name.Name, params, results, body), imports: used})
	case *ast.GenDecl:
		for i, s := range d.Specs {
			doc := d.Doc
			switch s := s.(type) {
			case *ast.TypeSpec:
				if !s.Name.IsExported() {
					continue
				}
				if s.Doc != nil {
					doc = s.Doc
				}
				out = append(out, decl{name: s.Name.Name, kind: "type", doc: docOf(doc), text: fmt.Sprintf("type %s = src.%s", s.Name.Name, s.Name.Name)})
			case *ast.ValueSpec:
				// in a group, a spec's own comment, or its line's; the group's comment heads the first
				if len(d.Specs) > 1 {
					switch {
					case s.Doc != nil:
						doc = s.Doc
					case s.Comment != nil:
						doc = s.Comment
					default:
						doc = nil
					}
					if i == 0 && d.Doc != nil {
						doc = &ast.CommentGroup{List: append(append([]*ast.Comment{}, d.Doc.List...), commentsOf(doc)...)}
					}
				} else if s.Doc != nil {
					doc = s.Doc
				}
				for _, n := range s.Names {
					if !n.IsExported() {
						continue
					}
					kind := "var"
					if d.Tok == token.CONST {
						kind = "const"
					}
					value := "src." + n.Name
					if byAddress[n.Name] {
						value = "&src." + n.Name
					}
					out = append(out, decl{name: n.Name, kind: kind, doc: docOf(doc), text: fmt.Sprintf("%s %s = %s", kind, n.Name, value)})
				}
			}
		}
	}
	return out
}

// fieldsText prints a parameter list with every parameter named, so the call can pass them on.
func fieldsText(fset *token.FileSet, list *ast.FieldList, imports, used map[string]string, named bool) string {
	var parts []string
	i := 0
	for _, f := range list.List {
		t := typeText(fset, f.Type, imports, used)
		if len(f.Names) == 0 {
			parts = append(parts, fmt.Sprintf("p%d %s", i, t))
			i++
			continue
		}
		for _, n := range f.Names {
			name := n.Name
			if name == "_" {
				name = fmt.Sprintf("p%d", i)
			}
			parts = append(parts, name+" "+t)
			i++
		}
	}
	return strings.Join(parts, ", ")
}

func resultsText(fset *token.FileSet, list *ast.FieldList, imports, used map[string]string) string {
	var parts []string
	for _, f := range list.List {
		t := typeText(fset, f.Type, imports, used)
		if len(f.Names) == 0 {
			parts = append(parts, t)
			continue
		}
		for _, n := range f.Names {
			parts = append(parts, n.Name+" "+t)
		}
	}
	if len(parts) == 1 && len(list.List[0].Names) == 0 {
		return parts[0]
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

// argsOf is the call's arguments, the names fieldsText gave, a variadic one spread.
func argsOf(list *ast.FieldList) string {
	var args []string
	i := 0
	for _, f := range list.List {
		names := []string{}
		if len(f.Names) == 0 {
			names = append(names, fmt.Sprintf("p%d", i))
			i++
		}
		for _, n := range f.Names {
			name := n.Name
			if name == "_" {
				name = fmt.Sprintf("p%d", i)
			}
			names = append(names, name)
			i++
		}
		for _, n := range names {
			if _, variadic := f.Type.(*ast.Ellipsis); variadic {
				n += "..."
			}
			args = append(args, n)
		}
	}
	return strings.Join(args, ", ")
}

// typeText prints a type as the root package names it: src's exported types by their aliases, other packages as imported.
func typeText(fset *token.FileSet, e ast.Expr, imports, used map[string]string) string {
	ast.Inspect(e, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				if p, ok := imports[id.Name]; ok {
					used[id.Name] = p
				}
			}
			return false
		}
		if id, ok := n.(*ast.Ident); ok && !id.IsExported() && id.Obj != nil && id.Obj.Kind == ast.Typ {
			fail("an exported function uses an unexported type: " + id.Name)
		}
		return true
	})
	var b bytes.Buffer
	if err := printer.Fprint(&b, fset, e); err != nil {
		fail(err.Error())
	}
	return b.String()
}

func commentsOf(g *ast.CommentGroup) []*ast.Comment {
	if g == nil {
		return nil
	}
	return g.List
}

func docOf(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}
	var b strings.Builder
	for _, c := range g.List {
		b.WriteString(c.Text + "\n")
	}
	return b.String()
}

func fail(message string) {
	fmt.Fprintln(os.Stderr, "forwards:", message)
	os.Exit(1)
}
